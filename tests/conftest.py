"""Shared pytest configuration: register the `slow` marker and gate it behind RUN_SLOW=1.

Tests never read the live `transcribe/profiles.json`: it is generated by `benchmarks.suite.make_profiles` and changes
with every calibration. They use the frozen pre-calibration table in `tests/data/profiles_uncalibrated.json`.
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest

UNCALIBRATED_PROFILES = Path(__file__).resolve().parent / "data" / "profiles_uncalibrated.json"


def pytest_configure(config: pytest.Config) -> None:
    config.addinivalue_line(
        "markers", "slow: loads real models or audio; runs only when RUN_SLOW=1"
    )


def pytest_collection_modifyitems(config: pytest.Config, items: list[pytest.Item]) -> None:
    if os.environ.get("RUN_SLOW") == "1":
        return
    skip_slow = pytest.mark.skip(reason="slow test: set RUN_SLOW=1 to run")
    for item in items:
        if "slow" in item.keywords:
            item.add_marker(skip_slow)


@pytest.fixture(autouse=True)
def _frozen_profiles(monkeypatch):
    from transcribe.auto import profiles

    monkeypatch.setattr(profiles, "PROFILES_PATH", UNCALIBRATED_PROFILES)
